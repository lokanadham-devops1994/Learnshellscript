#!/bin/bash
### Special Variables in Shell Script ###
echo "All the arguments are passed through the script: $@"
echo "The number of arguments passed through the script: $#"
echo "The first argument is: $1"
echo "The second argument is: $2"
echo "The third argument is: $3"
echo "All the arguments are passed through the script: $*"
echo "The name of the script is: $0"
echo "Real path of the script is: $(realpath $0)"
echo "Who is executing the script: $USER"
echo "name of the script is: $BASH"
echo "Present working directory is: $PWD"
echo "Home directory of the current user is: $HOME"
echo "The process ID of the current script is: $$"
sleep 10 &
echo "The process ID of the last background command is: $!"
wait $! # Wait for the background process to finish
echo "Line number of the last executed command is: $LINENO"
echo "The exit status of the last executed command is: $?"
echo "Total time excuted  for this script is: $SECONDS"
echo "The last foreground command is: $?"
echo "The last executed command is: $BASH_COMMAND"
echo "The last executed command is: $BASH_LINENO"
echo "The last executed command is: $BASH_SOURCE"
echo "The last executed command is: $BASH_SUBSHELL"
echo "The last executed command is: $BASH_VERSINFO"
echo "The last executed command is: $BASH_VERSION"
echo "The last executed command is: $BASHPID"
echo "The last executed command is: $BASH_ARGC"
echo "The last executed command is: $BASH_ARGV"